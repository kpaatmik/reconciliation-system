package com.kpaatmik.reconciliation.config;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

class ReconciliationFileResolverTest {
	@TempDir
	Path temp;

	private ReconciliationFileResolver resolver() {
		var p = new ReconciliationFileProperties();
		p.getInput().setDirectory(temp.resolve("in").toString());
		p.getInput().setBaselineFile("baseline.csv");
		p.getInput().setSourceFile("source.csv");
		p.getOutput().setDirectory(temp.resolve("out").toString());
		return new ReconciliationFileResolver(p);
	}

	@Test
	void resolvesInputOutputAndRunFiles() {
		var r = resolver();
		assertEquals(temp.resolve("in/baseline.csv").toAbsolutePath().normalize(), r.getBaselineFile());
		assertEquals(temp.resolve("in/source.csv").toAbsolutePath().normalize(), r.getSourceFile());
		assertTrue(r.getAuditFile("abc-123").endsWith("run-abc-123/audit.csv"));
		assertTrue(r.getSummaryFile("abc-123").endsWith("run-abc-123/reconciliation-summary.txt"));
	}

	@Test
	void rejectsUnsafeRunIds() {
		var r = resolver();
		assertThrows(IllegalArgumentException.class, () -> r.getRunOutputDirectory(null));
		assertThrows(IllegalArgumentException.class, () -> r.getRunOutputDirectory("../escape"));
		assertThrows(IllegalArgumentException.class, () -> r.getAuditFile("x/y"));
	}

	@Test
	void createsRunOutputDirectory() throws Exception {
		var r = resolver();
		r.prepareOutputDirectory("run_1");
		assertTrue(Files.isDirectory(r.getRunOutputDirectory("run_1")));
		assertTrue(Files.isWritable(r.getRunOutputDirectory("run_1")));
	}

	@Test
	void prepareOutputDirectoryThrowsIOExceptionWhenPathIsAFile() throws Exception {

		var r = resolver();

		String runId = "test-run";

		// Match the path generated by getRunOutputDirectory().
		Path outputDirectory = r.getRunOutputDirectory(runId);

		// Create the parent directory first.
		Files.createDirectories(outputDirectory.getParent());

		// Create a regular file where the output directory should be.
		Files.writeString(outputDirectory, "not a directory");

		assertThrows(IOException.class, () -> r.prepareOutputDirectory(runId));
	}

}
